// Package gen generates the TypeScript wire types for the Browser Companion
// from the canonical schema document (desktop/internal/browseripc/schema.json).
// The companion is a separate Node package, so the generated artifact is
// committed; cmd/browser-ipc-gen -check keeps it in sync on CI.
package gen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"reasonix/desktop/internal/browseripc"
)

// GenerateTypeScript renders the companion protocol types. It is deterministic:
// the schema keys are emitted in canonical order, so identical schema bytes
// always produce identical output.
func GenerateTypeScript() ([]byte, error) {
	schema := browseripc.SchemaJSON()
	var doc struct {
		Format          string `json:"format"`
		ProtocolVersion int    `json:"protocolVersion"`
		Limits          map[string]int
		ErrorCodes      []string
		Methods         []struct {
			Name   string
			Params schemaObject
			Result schemaObject
		}
		Events []struct {
			Name string
			Data schemaObject
		}
	}
	if err := json.Unmarshal(schema, &doc); err != nil {
		return nil, fmt.Errorf("parse schema: %w", err)
	}
	if doc.Format != "reasonix.browser.ipc.v1" {
		return nil, fmt.Errorf("unsupported schema format %q", doc.Format)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/browser-ipc-gen; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "export const BROWSER_SCHEMA_FORMAT = %q as const;\n", doc.Format)
	fmt.Fprintf(&b, "export const BROWSER_PROTOCOL_VERSION = %d as const;\n", doc.ProtocolVersion)
	fmt.Fprintf(&b, "export const BROWSER_SCHEMA_HASH = %q as const;\n", browseripc.SchemaHash())
	b.WriteString("\n")

	// Limits in canonical key order.
	limitKeys := make([]string, 0, len(doc.Limits))
	for k := range doc.Limits {
		limitKeys = append(limitKeys, k)
	}
	sort.Strings(limitKeys)
	b.WriteString("export const BROWSER_LIMITS = {\n")
	for _, k := range limitKeys {
		fmt.Fprintf(&b, "  %s: %d,\n", k, doc.Limits[k])
	}
	b.WriteString("} as const;\n\n")

	b.WriteString("export type BrowserErrorCode =\n")
	for _, code := range doc.ErrorCodes {
		fmt.Fprintf(&b, "  | %q\n", code)
	}
	b.WriteString("  ;\n\n")

	b.WriteString("export const BROWSER_ERROR_CODES = [\n")
	for _, code := range doc.ErrorCodes {
		fmt.Fprintf(&b, "  %q,\n", code)
	}
	b.WriteString("] as const;\n\n")

	b.WriteString("export type BrowserMethodName =\n")
	for i, m := range doc.Methods {
		fmt.Fprintf(&b, "  | %q\n", m.Name)
		if i == len(doc.Methods)-1 {
			b.WriteString("  ;\n")
		}
	}
	b.WriteString("\nexport const BROWSER_METHODS = [\n")
	for _, m := range doc.Methods {
		fmt.Fprintf(&b, "  %q,\n", m.Name)
	}
	b.WriteString("] as const;\n\n")

	b.WriteString("export type BrowserEventName =\n")
	for i, e := range doc.Events {
		fmt.Fprintf(&b, "  | %q\n", e.Name)
		if i == len(doc.Events)-1 {
			b.WriteString("  ;\n")
		}
	}
	b.WriteString("\nexport const BROWSER_EVENTS = [\n")
	for _, e := range doc.Events {
		fmt.Fprintf(&b, "  %q,\n", e.Name)
	}
	b.WriteString("] as const;\n\n")

	b.WriteString(`export interface BrowserRequest {
  protocolVersion: number;
  requestId: string;
  ownerId?: string;
  method: BrowserMethodName;
  params: unknown;
}

export interface BrowserErrorDetail {
  code: BrowserErrorCode;
  message: string;
}

export interface BrowserResponse {
  protocolVersion: number;
  requestId: string;
  result?: unknown;
  error?: BrowserErrorDetail;
}

export interface BrowserEvent {
  protocolVersion: number;
  event: {
    name: BrowserEventName;
    ownerId?: string;
    data: unknown;
  };
}
`)
	b.WriteString("\n")

	// Per-method params/result interfaces.
	for _, m := range doc.Methods {
		paramsName := tsName(m.Name) + "Params"
		if err := writeObject(&b, paramsName, m.Params); err != nil {
			return nil, fmt.Errorf("method %s: %w", m.Name, err)
		}
		resultName := tsName(m.Name) + "Result"
		if err := writeObject(&b, resultName, m.Result); err != nil {
			return nil, fmt.Errorf("method %s result: %w", m.Name, err)
		}
	}
	for _, e := range doc.Events {
		name := tsName(e.Name) + "EventData"
		if err := writeObject(&b, name, e.Data); err != nil {
			return nil, fmt.Errorf("event %s: %w", e.Name, err)
		}
	}
	// Exactly one trailing newline: no blank line at EOF (git diff --check).
	trimmed := bytes.TrimRight(b.Bytes(), "\n")
	return append(trimmed, '\n'), nil
}

type schemaObject struct {
	Type       string                     `json:"type"`
	Properties map[string]json.RawMessage `json:"properties"`
	Required   []string                   `json:"required"`
}

type schemaProp struct {
	Type  string        `json:"type"`
	Enum  []string      `json:"enum"`
	Items *schemaObject `json:"items"`
}

// tsName converts a dotted protocol name to an UpperCamel identifier:
// "tab.snapshot" -> "TabSnapshot".
func tsName(proto string) string {
	parts := strings.Split(proto, ".")
	var b strings.Builder
	for _, p := range parts {
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(p[1:])
	}
	return b.String()
}

func writeObject(b *bytes.Buffer, name string, obj schemaObject) error {
	if obj.Type != "object" {
		return fmt.Errorf("%s: expected object, got %q", name, obj.Type)
	}
	required := map[string]bool{}
	for _, r := range obj.Required {
		required[r] = true
	}
	fmt.Fprintf(b, "export interface %s {\n", name)
	keys := make([]string, 0, len(obj.Properties))
	for k := range obj.Properties {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		var p schemaProp
		if err := json.Unmarshal(obj.Properties[k], &p); err != nil {
			return fmt.Errorf("%s.%s: %w", name, k, err)
		}
		opt := "?"
		if required[k] {
			opt = ""
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", k, opt, tsType(p))
	}
	b.WriteString("}\n\n")
	return nil
}

func tsType(p schemaProp) string {
	if len(p.Enum) > 0 {
		parts := make([]string, len(p.Enum))
		for i, e := range p.Enum {
			parts[i] = fmt.Sprintf("%q", e)
		}
		return strings.Join(parts, " | ")
	}
	switch p.Type {
	case "string":
		return "string"
	case "integer":
		return "number"
	case "boolean":
		return "boolean"
	case "array":
		return "Array<" + tsItemType(p.Items) + ">"
	default:
		return "unknown"
	}
}

func tsItemType(item *schemaObject) string {
	if item == nil {
		return "unknown"
	}
	if item.Type == "object" {
		required := map[string]bool{}
		for _, r := range item.Required {
			required[r] = true
		}
		var b strings.Builder
		b.WriteString("{ ")
		keys := make([]string, 0, len(item.Properties))
		for k := range item.Properties {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for i, k := range keys {
			var p schemaProp
			_ = json.Unmarshal(item.Properties[k], &p) // schema is validated by parity tests
			opt := "?"
			if required[k] {
				opt = ""
			}
			fmt.Fprintf(&b, "%s%s: %s", k, opt, tsType(p))
			if i < len(keys)-1 {
				b.WriteString("; ")
			}
		}
		b.WriteString(" }")
		return b.String()
	}
	return tsType(schemaProp{Type: item.Type})
}
