import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { chromium } from "playwright";

const BASE = process.env.PERF_URL ?? "http://localhost:4399/perf.html";
const SHOTS = process.env.THEME_SCHEDULE_SHOTS;
if (SHOTS) await mkdir(SHOTS, { recursive: true });
const browser = await chromium.launch();
const errors = [];
try {
  for (const width of [1440, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 }, timezoneId: "America/New_York", reducedMotion: "reduce" });
    page.on("pageerror", (error) => errors.push(error.message));
    await page.clock.install({ time: new Date("2026-10-29T19:58:00-04:00") });
    await page.goto(`${BASE}?pref=en&turns=0`);
    await page.waitForSelector(".app");
    await page.keyboard.press("Meta+Comma");
    await page.getByRole("tab", { name: /Appearance/ }).click();
    await page.locator('[data-action="appearance.scheme"][data-value="scheduled"]').click();
    const start = page.getByLabel("Dark mode starts", { exact: true });
    const end = page.getByLabel("Light mode resumes", { exact: true });
    assert.equal(await start.inputValue(), "20:00");
    assert.equal(await end.inputValue(), "07:00");
    const boxes = await page.locator('#set-mode input[type="time"]').evaluateAll((inputs) => inputs.map((input) => {
      const box = input.getBoundingClientRect();
      return { left: box.left, right: box.right, width: box.width };
    }));
    assert.ok(boxes.every((box) => box.width > 0 && box.left >= 0 && box.right <= width));
    await page.clock.pauseAt(new Date("2026-10-29T19:59:59-04:00"));
    assert.equal(await page.locator("html").getAttribute("data-theme"), "light");
    assert.equal(await start.evaluate((input) => getComputedStyle(input).colorScheme), "light");
    if (SHOTS) {
      await page.locator("#set-mode").scrollIntoViewIfNeeded();
      await page.screenshot({ path: `${SHOTS}/after-light-${width}.png`, animations: "disabled" });
    }
    await page.clock.runFor(1000);
    assert.equal(await page.locator("html").getAttribute("data-theme"), "dark");
    assert.equal(await start.evaluate((input) => getComputedStyle(input).colorScheme), "dark");
    await page.clock.runFor(1000);
    if (SHOTS) await page.screenshot({ path: `${SHOTS}/after-dark-${width}.png`, animations: "disabled" });
    await page.clock.fastForward("03:59:58");
    assert.equal(await page.locator("html").getAttribute("data-theme"), "dark");
    await page.clock.runFor(1000);
    assert.equal(await page.locator("html").getAttribute("data-theme"), "dark");
    await page.clock.fastForward("07:00:00");
    assert.equal(await page.locator("html").getAttribute("data-theme"), "light");
    await start.fill("21:30");
    await end.fill("06:15");
    await page.clock.resume();
    await page.reload();
    await page.waitForSelector(".app");
    await page.keyboard.press("Meta+Comma");
    await page.getByRole("tab", { name: /Appearance/ }).click();
    assert.equal(await start.inputValue(), "21:30");
    assert.equal(await end.inputValue(), "06:15");
    assert.equal(await page.locator('[data-value="scheduled"]').getAttribute("aria-pressed"), "true");
    await page.clock.setSystemTime(new Date("2026-10-30T23:00:00-04:00"));
    await page.evaluate(() => window.dispatchEvent(new Event("focus")));
    assert.equal(await page.locator("html").getAttribute("data-theme"), "dark");
    await page.clock.setSystemTime(new Date("2026-10-31T09:00:00-04:00"));
    await page.evaluate(() => document.dispatchEvent(new Event("visibilitychange")));
    assert.equal(await page.locator("html").getAttribute("data-theme"), "light");
    await page.locator('[data-action="appearance.scheme"][data-value="dark"]').click();
    assert.equal(await start.count(), 0);
    await page.emulateMedia({ colorScheme: "light" });
    assert.equal(await page.locator("html").getAttribute("data-theme"), "dark");
    await page.locator('[data-action="appearance.scheme"][data-value="auto"]').click();
    assert.equal(await page.locator("html").getAttribute("data-theme"), "light");
    await page.emulateMedia({ colorScheme: "dark" });
    await page.waitForFunction(() => document.documentElement.dataset.theme === "dark");
    console.log(`ok ${width}px: exact boundaries, midnight, saved controls/reload, focus/visibility resume, explicit/system modes`);
    await page.close();
  }
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, timezoneId: "America/New_York", reducedMotion: "reduce" });
  page.on("pageerror", (error) => errors.push(error.message));
  await page.clock.install({ time: new Date("2026-11-01T00:59:00-04:00") });
  await page.goto(`${BASE}?pref=zh&turns=0&pack=sky`);
  await page.waitForSelector(".app");
  await page.keyboard.press("Meta+Comma");
  await page.getByRole("tab", { name: /外观/ }).click();
  await page.locator('[data-action="appearance.scheme"][data-value="scheduled"]').click();
  await page.getByLabel("深色开始时间", { exact: true }).fill("01:30");
  await page.getByLabel("恢复浅色时间", { exact: true }).fill("01:45");
  await page.clock.pauseAt(new Date("2026-11-01T01:29:59-04:00"));
  await page.clock.runFor(1000);
  assert.equal(await page.locator("html").getAttribute("data-theme"), "dark");
  assert.equal(await page.locator("html").getAttribute("data-pack"), "bench-sky");
  assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue("--page").trim()), "#080D10");
  await page.clock.fastForward("15:00");
  assert.equal(await page.locator("html").getAttribute("data-theme"), "light");
  await page.clock.fastForward("45:00");
  assert.equal(await page.locator("html").getAttribute("data-theme"), "dark");
  await page.clock.fastForward("15:00");
  assert.equal(await page.locator("html").getAttribute("data-theme"), "light");
  assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue("--page").trim()), "#F2F6F8");
  await page.getByLabel("深色开始时间", { exact: true }).fill("02:30");
  await page.getByLabel("恢复浅色时间", { exact: true }).fill("04:00");
  await page.clock.setSystemTime(new Date("2026-03-08T01:59:59-05:00"));
  await page.evaluate(() => window.dispatchEvent(new Event("focus")));
  assert.equal(await page.locator("html").getAttribute("data-theme"), "light");
  await page.clock.fastForward(1000);
  assert.equal(await page.locator("html").getAttribute("data-theme"), "dark");
  await page.clock.fastForward("01:00:00");
  assert.equal(await page.locator("html").getAttribute("data-theme"), "light");
  console.log("ok Chinese controls, active pack repaint, skipped and repeated DST hour transitions");
  await page.close();
  assert.deepEqual(errors, []);
} finally {
  await browser.close();
}
