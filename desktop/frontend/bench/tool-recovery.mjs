import path from "node:path";
import os from "node:os";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
process.env.PLAYWRIGHT_BROWSERS_PATH = path.join(root, ".pw-browsers");
const { chromium } = await import("playwright");
const server = await createServer({ root, logLevel: "error", server: { host: "127.0.0.1", port: 0 } });
await server.listen();
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1000, height: 720 } });
const errors = [];
page.on("pageerror", e => errors.push(e.message));
const check = (ok, msg) => { if (!ok) throw new Error(msg); console.log("PASS " + msg); };
try {
  const base = server.resolvedUrls.local[0];
  await page.goto(base + "bench/tool-recovery.html");
  const buttons = page.locator("button");
  await buttons.first().waitFor();
  const viewportHeight = await page.locator(".transcript").evaluate(el => el.clientHeight);
  check(await buttons.nth(1).isDisabled(), "confirmation requires inspection");
  check(await buttons.nth(3).isDisabled(), "unknown writer cannot be retried");
  await buttons.nth(0).click();
  await page.waitForFunction(() => !document.querySelectorAll("button")[1].disabled);
  await page.locator("details details > summary").click();
  check((await page.locator("pre").textContent()).includes("local receipt"), "inspect shows stored argument receipt");
  check(await page.locator(".transcript").evaluate(el => el.clientHeight) === viewportHeight, "recovery details do not resize the transcript viewport");
  await page.screenshot({ path: path.join(os.tmpdir(), "reasonix-tool-recovery.png") });
  await buttons.nth(1).click();
  await page.waitForFunction(() => document.querySelectorAll("button").length === 1);
  await buttons.first().click();
  check(JSON.stringify(await page.evaluate(() => window.recoveryFixture.actions)) === '["inspect","confirm","resume"]', "inspect confirm resume uses backend actions");
  await page.reload(); await buttons.first().waitFor();
  await page.evaluate(() => { window.holdRecovery = true; });
  await buttons.first().click();
  await page.evaluate(() => window.recoveryFixture.render("new-tab"));
  await page.waitForFunction(() => document.querySelectorAll("section").length === 0);
  await page.evaluate(() => window.recoveryFixture.release());
  check(!(await page.locator("body").textContent()).includes("STALE_RESULT"), "late inspection cannot overwrite a new session");
  check(errors.length === 0, "no browser errors: " + errors.join(";"));
} finally { await browser.close(); await server.close(); }
